"""Generate the SYNTHETIC targeted evaluation set: one case per situation the matching policy must handle.

Every record is invented, like the other evaluation sets. The output is deterministic (its own fixed seed)
and is written once. The original sets (`synthetic_pairs.json`, `synthetic_pairs_extended.json`) are not
touched and not regenerated by this script.

Each lost query carries a `case` label. True matches carry the same label, so recall is reported per case.
Hard negatives carry `negative_type`, so false positives are reported per type, as in the other sets.

Case labels (true matches):
  tc-colour-category-location  colour, category and place only; nothing identifying on either side
  tc-colour-description        colour plus a distinctive word in both descriptions (no feature field)
  tc-common-brand-feature      common brand plus the same distinctive feature on both sides
  tc-missing-brand             the found report has no brand; the feature matches
  tc-missing-feature           the found report has no feature; brand and colour match, description generic
  tc-roman-urdu                Roman-Urdu description with a marking
  tc-misspelled                misspelt colour, brand and marking on both sides
  tc-generic-template          templated description, colour and brand, no feature
  tc-distinctive-description   free text with distinctive words (engraved name, cracked glass)

Hard-negative types (each a different physical item):
  tg-same-attrs-other          same category, colour and place; generic text; nothing identifying
  tg-common-brand-other        same brand and colour and place; a different feature
  tg-different-brand-same-feature  same feature and colour; a different brand

    python -m evaluation.generate_targeted
"""

import json
import random
from datetime import datetime, timedelta, timezone

from evaluation.generate_dataset import HERE, RGB, SHAPE, load_places

OUT_FILE = HERE / "data" / "synthetic_pairs_targeted.json"
SEED = 20261004
QUERIES_PER_CASE = 5

TRUE_CASES = ["tc-colour-category-location", "tc-colour-description", "tc-common-brand-feature",
              "tc-missing-brand", "tc-missing-feature", "tc-roman-urdu", "tc-misspelled",
              "tc-generic-template", "tc-distinctive-description"]

ITEMS = {
    "backpack": dict(lost_category="Backpack", found_categories=["Bag", "Backpack"], noun="backpack",
                     colors=["black", "navy blue", "grey"], brands=["JanSport", "Herschel", "Skybags"],
                     features=["name tag with initials inside the pocket", "torn left strap",
                               "red keychain on the front zipper", "cricket team sticker on the front pocket"]),
    "watch": dict(lost_category="Watch", found_categories=["Watch", "Wristwatch"], noun="watch",
                  colors=["black", "silver", "gold"], brands=["Casio", "Titan", "Fossil"],
                  features=["engraved back cover", "leather strap with a scratch"]),
    "keys": dict(lost_category="Keys", found_categories=["Keys", "Key ring"], noun="car keys",
                 colors=["silver", "black"], brands=["Honda", "Toyota"],
                 features=["football shaped keychain", "blue plastic tag with a number"]),
    "phone": dict(lost_category="Phone", found_categories=["Phone", "Mobile"], noun="phone",
                  colors=["black", "silver", "blue"], brands=["Samsung", "Infinix"],
                  features=["cracked screen corner", "blue case with a sticker"]),
}
ITEM_KEYS = list(ITEMS)

# Typos used by the misspelled case. The found side uses a different typo, as people do.
MISSPELL_BRAND = {"JanSport": ("JanSprot", "Jansprt"), "Casio": ("Casoi", "Cassio"), "Honda": ("Hnda", "Hondaa"),
                  "Samsung": ("Samsng", "Samsumg"), "Titan": ("Titen", "Tittan"), "Toyota": ("Toyta", "Toyot"),
                  "Herschel": ("Hershel", "Herchel"), "Fossil": ("Fosil", "Fossill"), "Skybags": ("Skybag", "Skybgs"),
                  "Infinix": ("Infinx", "Infinis")}
MISSPELL_COLOR = {"black": ("blak", "blck"), "silver": ("sliver", "silvr"), "blue": ("blu", "bleu"),
                  "navy blue": ("navy bleu", "navy blu"), "grey": ("gray", "grye"), "gold": ("gold", "goldd")}
URDU_COLOR = {"black": "kala", "silver": "chandi jaisa", "blue": "neela", "navy blue": "neela", "grey": "slate jaisa",
              "gold": "sunehri"}
URDU_CUE = {"backpack": "bag", "watch": "ghari", "keys": "chabi", "phone": "phone"}
ENGRAVING = ["AYESHA 2019", "AK-19", "BILAL 7", "UET 88"]


def _iso(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _clock(dt: datetime) -> str:
    h = dt.hour % 12 or 12
    return f"{h}:{dt.minute:02d} {'PM' if dt.hour >= 12 else 'AM'}"


def _jitter(rng: random.Random, lat: float, lng: float) -> tuple[float, float]:
    return round(lat + rng.uniform(-0.0012, 0.0012), 6), round(lng + rng.uniform(-0.0012, 0.0012), 6)


def _lost(rng, *, qid, case, item_key, color, brand, feature, desc, when, place):
    it = ITEMS[item_key]
    return dict(id=qid, role="owner_query", case=case, item_type=item_key, name=f"{color} {it['noun']}".title(),
                category=it["lost_category"], description=desc, color=color, brand=brand,
                distinctive_features=feature, private_details="Inside: a notebook and a small pouch.",
                date_time=_iso(when), location=place["name"], location_type="predefined",
                place_key=place["key"], latitude=place["lat"], longitude=place["lng"], zone="campus",
                image={"fill": list(RGB.get(color, (120, 120, 120))), "shape": SHAPE[item_key]})


def _found(rng, *, case, role, item_key, color, brand, feature, desc, when, place, origin=None,
           negative_type=None, category=None):
    it = ITEMS[item_key]
    lat, lng = _jitter(rng, place["lat"], place["lng"])
    row = dict(role=role, case=case, origin=origin, item_type=item_key,
               name=f"{color or ''} {it['noun']}".strip().title(),
               category=category or rng.choice(it["found_categories"]), description=desc, color=color, brand=brand,
               distinctive_features=feature, private_details="Contains a small notebook and a charger.",
               date_time=_iso(when), location=f"Near {place['name']}", location_type="gps", place_key=None,
               latitude=lat, longitude=lng, zone="campus",
               image={"fill": list(RGB.get(color or "", (120, 120, 120))), "shape": SHAPE[item_key]})
    if negative_type:
        row["negative_type"] = negative_type
    return row


def _true_pair(rng, case, q_id, item_key, place, base_when):
    """One lost query and its true match for a case. Returns (lost row, found row)."""
    it = ITEMS[item_key]
    color = rng.choice(it["colors"])
    brand = rng.choice(it["brands"])
    feature = rng.choice(it["features"])
    noun = it["noun"]
    t_lost, t_found = base_when, base_when + timedelta(hours=rng.randint(1, 12))
    p = place["name"]
    engrave = rng.choice(ENGRAVING)
    f_place = place  # the found report is at the same place or near it (GPS jitter applies)

    if case == "tc-colour-category-location":
        l_desc = f"Lost my {color} {noun} near {p} around {_clock(t_lost)}."
        f_desc = f"Found a {color} {noun} near {p} at about {_clock(t_found)}."
        l_b, l_f, f_b, f_f = None, None, None, None
    elif case == "tc-colour-description":
        l_desc = f"Lost my {color} {noun} with a calculus notebook inside, near {p}."
        f_desc = f"Found a {color} {noun} near {p}. Calculus notes inside."
        l_b, l_f, f_b, f_f = None, None, None, None
    elif case == "tc-common-brand-feature":
        l_desc = f"Lost my {color} {brand} {noun} near {p} around {_clock(t_lost)}."
        f_desc = f"Found a {color} {brand} {noun} near {p} at about {_clock(t_found)}."
        l_b, l_f, f_b, f_f = brand, feature, brand, feature
    elif case == "tc-missing-brand":
        l_desc = f"Lost my {color} {brand} {noun} near {p} around {_clock(t_lost)}."
        f_desc = f"Found a {color} {noun} near {p} at about {_clock(t_found)}."
        l_b, l_f, f_b, f_f = brand, feature, None, feature
    elif case == "tc-missing-feature":
        l_desc = f"Lost my {color} {brand} {noun} near {p} around {_clock(t_lost)}."
        f_desc = f"Found a {color} {brand} {noun} near {p} at about {_clock(t_found)}."
        l_b, l_f, f_b, f_f = brand, feature, brand, None
    elif case == "tc-roman-urdu":
        word = URDU_CUE[item_key]
        l_desc = f"Mera {URDU_COLOR[color]} {brand} {word} {p} ke paas kho gaya. Us par initials AK likhe hain."
        f_desc = f"{URDU_COLOR[color].capitalize()} {brand} {word} mila {p} ke paas. Initials AK likhe hue hain."
        l_b, l_f, f_b, f_f = brand, None, brand, None
    elif case == "tc-misspelled":
        lb1, lb2 = MISSPELL_BRAND[brand]
        lc1, lc2 = MISSPELL_COLOR[color]
        l_desc = f"Lost my {lc1} {lb1} {noun} near {p}. Initails AK inside."
        f_desc = f"Found a {lc2} {lb2} {noun} near {p}. Initails AK inside."
        l_b, l_f, f_b, f_f = None, None, None, None
        color_l, color_f = lc1, lc2
        return _build_pair(rng, case, q_id, item_key, place, t_lost, t_found, color, brand, feature,
                           l_desc, f_desc, None, None, None, None, color_override=(color_l, color_f))
    elif case == "tc-generic-template":
        l_desc = f"Lost my {color} {brand} {noun} near {p} around {_clock(t_lost)}."
        f_desc = f"Found a {color} {brand} {noun} near {p} at about {_clock(t_found)}."
        l_b, l_f, f_b, f_f = brand, None, brand, None
    elif case == "tc-distinctive-description":
        l_desc = (f"{brand} {noun} in {color}, engraved '{engrave}' on the back, glass cracked at 3 o'clock, "
                  f"near {p}.")
        f_desc = (f"{color.capitalize()} {brand} {noun} with {engrave} engraved on back, glass cracked at 3 o'clock, "
                  f"found near {p}.")
        l_b, l_f, f_b, f_f = brand, None, brand, None
    else:
        raise ValueError(case)
    return _build_pair(rng, case, q_id, item_key, place, t_lost, t_found, color, brand, feature, l_desc, f_desc,
                       l_b, l_f, f_b, f_f)


def _build_pair(rng, case, q_id, item_key, place, t_lost, t_found, color, brand, feature, l_desc, f_desc,
                l_b, l_f, f_b, f_f, color_override=None):
    lc, fc = color_override if color_override else (color, color)
    lost = _lost(rng, qid=q_id, case=case, item_key=item_key, color=lc, brand=l_b, feature=l_f, desc=l_desc,
                 when=t_lost, place=place)
    found = _found(rng, case=case, role="true_match", item_key=item_key, color=fc, brand=f_b, feature=f_f,
                   desc=f_desc, when=t_found, place=place, origin=q_id)
    return lost, found


def _hard_negatives(rng, q_id, case_color, item_key, brand, feature, place, base_when, other_places):
    """The three hard-negative types for one query. Each is a different physical item."""
    it = ITEMS[item_key]
    out = []
    # Same category, colour and place, nothing identifying.
    out.append(_found(rng, case="tg-same-attrs-other", role="hard_negative", item_key=item_key,
                      color=case_color, brand=None, feature=None,
                      desc=f"Found a {case_color} {it['noun']} near {place['name']} at about "
                           f"{_clock(base_when + timedelta(hours=3))}.",
                      when=base_when + timedelta(hours=rng.randint(2, 6)), place=place, origin=q_id,
                      negative_type="tg-same-attrs-other", category=it["found_categories"][0]))
    # Same brand (when the item has one), colour and place, different feature.
    other_feature = rng.choice([f for f in it["features"] if f != feature])
    out.append(_found(rng, case="tg-common-brand-other", role="hard_negative", item_key=item_key,
                      color=case_color, brand=brand, feature=other_feature,
                      desc=f"Found a {case_color} {brand} {it['noun']} near {place['name']}.",
                      when=base_when + timedelta(hours=rng.randint(2, 8)), place=place, origin=q_id,
                      negative_type="tg-common-brand-other"))
    # Same feature and colour, different brand, a nearby place.
    other_brand = rng.choice([b for b in it["brands"] if b != brand] or [None])
    near = rng.choice([p for p in other_places])
    out.append(_found(rng, case="tg-different-brand-same-feature", role="hard_negative", item_key=item_key,
                      color=case_color, brand=other_brand, feature=feature,
                      desc=f"Found a {case_color} {other_brand or ''} {it['noun']} near {near['name']}.".replace("  ", " "),
                      when=base_when + timedelta(hours=rng.randint(2, 8)), place=near, origin=q_id,
                      negative_type="tg-different-brand-same-feature"))
    return out


def _easy_negatives(rng, places, n: int):
    rows = []
    for _ in range(n):
        key = rng.choice(ITEM_KEYS)
        when = datetime(2026, 9, 1, tzinfo=timezone.utc) + timedelta(days=rng.randint(0, 28), hours=rng.randint(8, 17))
        color = rng.choice(ITEMS[key]["colors"])
        rows.append(_found(rng, case="unrelated", role="easy_negative", item_key=key, color=color, brand=None,
                           feature=None, desc=f"Found a {color} {ITEMS[key]['noun']} near campus.",
                           when=when, place=rng.choice(places), negative_type="unrelated"))
    return rows


def build() -> dict:
    rng = random.Random(SEED)
    places = load_places()
    base = datetime(2026, 9, 1, tzinfo=timezone.utc)
    lost_rows, found_rows = [], []
    n = 0
    for case in TRUE_CASES:
        for k in range(QUERIES_PER_CASE):
            n += 1
            q_id = f"L{n:03d}"
            item_key = ITEM_KEYS[(n - 1) % len(ITEM_KEYS)]
            place = rng.choice(places)
            when = base + timedelta(days=rng.randint(0, 28), hours=rng.randint(8, 17))
            lost, found = _true_pair(rng, case, q_id, item_key, place, when)
            lost_rows.append(lost)
            found_rows.append(found)
            # Hard negatives use the query's colour, brand and feature, so each one looks like the query's item.
            others = [p for p in places if p["key"] != place["key"]]
            color = lost["color"] or ITEMS[item_key]["colors"][0]
            brand = lost["brand"] or ITEMS[item_key]["brands"][0]
            feature = lost["distinctive_features"] or ITEMS[item_key]["features"][0]
            found_rows.extend(_hard_negatives(rng, q_id, color, item_key, brand, feature, place, when, others))
    found_rows.extend(_easy_negatives(rng, places, 30))

    for i, row in enumerate(found_rows, 1):
        row["id"] = f"F{i:03d}"
    true_pairs = [[r["origin"], r["id"]] for r in found_rows if r["role"] == "true_match"]
    counts = {"lost": len(lost_rows), "found": len(found_rows), "true_pairs": len(true_pairs)}
    return {
        "dataset": "SYNTHETIC",
        "notice": ("Invented for offline evaluation. Not real user reports, people or locations history. "
                   "Coordinates are campus place points from app/geo/uet_lahore.json. Photos are rendered "
                   "from simple synthetic shapes, not real photographs. Targeted cases, not a random sample."),
        "generator": "backend/evaluation/generate_targeted.py",
        "seed": SEED,
        "counts": counts,
        "lost": lost_rows,
        "found": found_rows,
        "true_pairs": true_pairs,
    }


def main() -> None:
    data = build()
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT_FILE} {data['counts']}")


if __name__ == "__main__":
    main()
